"""Write worlds/mass_effect_le1/levelup.py from LE1's level-up 2DAs (LevelUp_Experience, LevelUp_Credits in Engine.pcc).

usage: python tools/le1mod/export_levelup.py <LE1 game folder (...\\Game\\ME1)>
"""
from __future__ import annotations

import os
import sys

import le1pkg
import twoda

TABLES = {
    "XP_REWARDS": ("BIOG_2DA_LevelUp_X.LevelUp_Experience", ("XPNeeded", "MinorQuest", "MediumQuest", "MajorQuest", "MainPlot")),
    "CREDIT_REWARDS": ("BIOG_2DA_LevelUp_X.LevelUp_Credits", ("MinorReward", "SmallReward", "MediumReward", "LargeReward", "MajorReward")),
}
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "worlds", "mass_effect_le1", "levelup.py")


def main(game: str) -> None:
    dll = os.path.join(game, "Binaries", "Win64", "oo2core_8_win64.dll")
    pkg = le1pkg.read(os.path.join(game, "BioGame", "CookedPCConsole", "Engine.pcc"), dll)
    lines = ['"""LE1 level-up reward tables (generated by tools/le1mod/export_levelup.py from Engine.pcc; do not edit).',
             "", "Row = squad level (index 0 is level 1). The squad gets these from quests (XP) and rewards (credits).", '"""', ""]
    for name, (export, columns) in TABLES.items():
        _, rows = twoda.read(pkg, pkg.find("Bio2DANumberedRows", export))
        levels = sorted(rows)
        if levels != list(range(1, len(levels) + 1)):
            raise SystemExit(f"{export}: rows are not levels 1..n")
        lines.append(f"{name}_COLUMNS = {columns!r}")
        lines.append(f"{name}: tuple[tuple[int, ...], ...] = (")
        lines += [f"    {tuple(int(rows[level][column]) for column in columns)!r},  # level {level}" for level in levels]
        lines += [")", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines))
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main(sys.argv[1])
